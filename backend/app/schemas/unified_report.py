"""Unified Threat Report Schema for Part 16.

Combines standardized findings, deterministic risk assessment, external intelligence,
grounded user recommendations, and blockchain integrity placeholders into a validated payload.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, ConfigDict, Field

from backend.app.engines.ai.schemas import AiAnalysisResult
from backend.app.schemas.evidence import CheckStatus, StandardizedFinding
from backend.app.schemas.risk import DeterministicRiskAssessment


def get_utc_now() -> datetime:
    """Return timezone-aware UTC datetime."""
    return datetime.now(timezone.utc)


class ReportIntegrityInfo(BaseModel):
    """Metadata regarding report canonical representation and Web3/Blockchain anchoring."""

    model_config = ConfigDict(extra="forbid")

    canonical_sha256: str = Field(
        ...,
        description="Deterministic SHA-256 hash computed over canonical report contents.",
    )
    blockchain_status: str = Field(
        default="NOT_REGISTERED",
        description="On-chain registration state: NOT_REGISTERED, LOCAL_ONLY, or ANCHORED.",
    )
    network: Optional[str] = Field(None, description="Blockchain network identifier if anchored.")
    contract_address: Optional[str] = Field(None, description="Smart contract address if anchored.")
    transaction_hash: Optional[str] = Field(None, description="Transaction hash if anchored.")
    disclaimer: str = Field(
        default="A cryptographic report hash proves the integrity of this specific data representation; it does not prove the external factual accuracy of the report.",
        description="Disclaimer on cryptographic hash semantics.",
    )


class ThreatIntelligenceSummary(BaseModel):
    """Summary of threat intelligence provider queries."""

    model_config = ConfigDict(extra="forbid")

    provider_name: str = Field(default="local_threat_intel")
    status: CheckStatus = Field(default=CheckStatus.UNAVAILABLE)
    is_malicious: Optional[bool] = Field(None)
    threat_types: List[str] = Field(default_factory=list)
    reputation_score: Optional[int] = Field(None)
    details: Dict[str, Any] = Field(default_factory=dict)


class UnifiedThreatReport(BaseModel):
    """Unified threat intelligence report generated by CyberShield AI 2.0."""

    model_config = ConfigDict(extra="forbid")

    scan_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Globally unique correlation identifier for this threat scan.",
    )
    submitted_input: str = Field(..., description="Sanitized submitted target (URL, email, SMS).")
    input_type: str = Field(..., description="Type of input analyzed: url, email, sms.")
    timestamp: datetime = Field(
        default_factory=get_utc_now,
        description="Timezone-aware UTC timestamp of report completion.",
    )
    risk_assessment: DeterministicRiskAssessment = Field(
        ...,
        description="Synthesized deterministic risk evaluation and scoring.",
    )
    technical_findings: List[StandardizedFinding] = Field(
        default_factory=list,
        description="Collection of standardized technical findings from all modules.",
    )
    threat_intelligence: ThreatIntelligenceSummary = Field(
        default_factory=ThreatIntelligenceSummary,
        description="Summary of external threat intelligence reputation checks.",
    )
    ai_analysis: Optional[AiAnalysisResult] = Field(
        None,
        description="Isolated AI contextual analysis; strictly separated from technical findings.",
    )
    recommendations: List[str] = Field(
        default_factory=list,
        description="Actionable defensive guidance grounded in actual findings.",
    )
    security_check_status: Dict[str, CheckStatus] = Field(
        default_factory=dict,
        description="Explicit execution status of each upstream investigation module.",
    )
    limitations: List[str] = Field(
        default_factory=list,
        description="Explicit operational caveats, partial investigations, or unavailable checks.",
    )
    report_integrity: ReportIntegrityInfo = Field(
        ...,
        description="Canonical hash and blockchain anchoring metadata.",
    )
